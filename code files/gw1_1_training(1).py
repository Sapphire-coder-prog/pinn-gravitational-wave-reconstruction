class StrainDataset(Dataset):
    def __init__(self, npz_path, split, limit=None):
        d = np.load(npz_path, allow_pickle=True)
        mask = d["split"] == split
        idx = np.where(mask)[0]
        if limit is not None:
            idx = idx[:limit]
        self.noisy = d["noisy"][idx]
        self.clean = d["clean"][idx]
        self.chirp_mass = d["chirp_mass"][idx].astype(np.float32)
        self.total_mass = d["total_mass"][idx].astype(np.float32)
        self.eta = d["eta"][idx].astype(np.float32)

    def __len__(self):
        return len(self.noisy)

    def __getitem__(self, i):
        return {
            "noisy": torch.tensor(self.noisy[i] * STRAIN_SCALE, dtype=torch.float32),
            "clean": torch.tensor(self.clean[i] * STRAIN_SCALE, dtype=torch.float32),
            "chirp_mass": torch.tensor(self.chirp_mass[i]),
            "total_mass": torch.tensor(self.total_mass[i]),
            "eta": torch.tensor(self.eta[i]),
        }


