def soft_loss(model, out, batch, w_physics):
    data_loss = torch.nn.functional.mse_loss(out["recon_strain"], batch["clean"])
    mchirp_loss = torch.nn.functional.mse_loss(out["chirp_mass"], batch["chirp_mass"])
    # DEBUG_SKIP_PHYSICS lets us bisect the GPU crash
    if DEBUG_SKIP_PHYSICS:
        physics_loss = torch.tensor(0.0, device=out["recon_strain"].device)
    else:
        physics_loss = model.physics_residual(out["recon_strain"], out["chirp_mass"])
    aux_loss = (torch.nn.functional.mse_loss(out["total_mass"], batch["total_mass"])
                + torch.nn.functional.mse_loss(out["eta"], batch["eta"]))
    total = data_loss + W_MCHIRP * mchirp_loss + w_physics * physics_loss + W_AUX * aux_loss
    return total


def hard_loss(out, batch):
    data_loss = torch.nn.functional.mse_loss(out["recon_strain"], batch["clean"])
    mchirp_loss = torch.nn.functional.mse_loss(out["chirp_mass"], batch["chirp_mass"])
    aux_loss = (torch.nn.functional.mse_loss(out["total_mass"], batch["total_mass"])
                + torch.nn.functional.mse_loss(out["eta"], batch["eta"]))
    total = data_loss + W_MCHIRP * mchirp_loss + W_AUX * aux_loss
    return total


def physics_weight_schedule(epoch):
    if epoch < PHYSICS_WARMUP_START:
        return 0.0
    if epoch >= PHYSICS_WARMUP_END:
        return W_PHYSICS_MAX
    return W_PHYSICS_MAX * (epoch - PHYSICS_WARMUP_START) / (PHYSICS_WARMUP_END - PHYSICS_WARMUP_START)


def run_epoch(model, loader, device, optimizer, w_physics, train):
    model.train() if train else model.eval()
    total_loss, total_mchirp_err, n_samples = 0.0, 0.0, 0

    context = torch.enable_grad() if train else torch.no_grad()
    with context:
        for batch in loader:
            batch = {k: v.to(device) for k, v in batch.items()}
            if train:
                optimizer.zero_grad()

            out = model(batch["noisy"])
            if MODEL_TYPE == "soft":
                loss = soft_loss(model, out, batch, w_physics)
            else:
                loss = hard_loss(out, batch)

            if train:
                loss.backward()
                # gradient clipping for BOTH models now (was hard-only) --
                # a real run showed the soft model's physics term can also
                # produce catastrophic gradient spikes when w_physics turns on
                max_norm = 1.0 if MODEL_TYPE == "hard" else 5.0
                torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=max_norm)
                optimizer.step()

            bs = batch["noisy"].shape[0]
            total_loss += loss.item() * bs
            rel_err_pct = (torch.abs(out["chirp_mass"] - batch["chirp_mass"]) / batch["chirp_mass"]) * 100
            total_mchirp_err += rel_err_pct.sum().item()
            n_samples += bs

    return total_loss / n_samples, total_mchirp_err / n_samples


