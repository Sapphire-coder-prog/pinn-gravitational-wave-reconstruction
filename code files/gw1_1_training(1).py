class HardConstrainedModel(nn.Module):
    def __init__(self, seg_len=16384):
        super().__init__()
        self.encoder = SharedEncoder()
        self.chirp_mass_head = ChirpMassHead()
        self.phase_head = nn.Sequential(nn.Linear(128, 64), nn.ReLU(), nn.Linear(64, 2))  # (cos, sin)
        self.amplitude_head = nn.Sequential(nn.Linear(128, 64), nn.ReLU(), nn.Linear(64, 1))
        self.aux_heads = AuxMassHeads()
        self.register_buffer("t_grid", torch.linspace(0, seg_len * DELTA_T, seg_len))

    def forward(self, noisy_strain):
        z = self.encoder(noisy_strain.unsqueeze(1))
        chirp_mass = self.chirp_mass_head(z)

        cos_sin = self.phase_head(z)
        cos_sin = cos_sin / (cos_sin.norm(dim=-1, keepdim=True) + 1e-8)
        phi_c = torch.atan2(cos_sin[:, 1], cos_sin[:, 0])

        amplitude = _rescale_sigmoid(self.amplitude_head(z), A_MIN, A_MAX).squeeze(-1)
        total_mass, eta = self.aux_heads(z)

        recon_strain = self._generate(chirp_mass, phi_c, amplitude)

        return {
            "recon_strain": recon_strain,
            "chirp_mass": chirp_mass,
            "total_mass": total_mass,
            "eta": eta,
            "phi_c": phi_c,
            "amplitude": amplitude,
        }

    def _generate(self, chirp_mass, phi_c, amplitude):
        """The analytic PN generator -- ARCHITECTURE_SPEC.md 3.2. This IS the
        hard constraint: strain can only ever be a function that satisfies
        the leading-order PN frequency law, by construction."""
        batch = chirp_mass.shape[0]
        t = self.t_grid.unsqueeze(0).expand(batch, -1)          
        mchirp = chirp_mass.unsqueeze(-1)                        

        f_t = pn_frequency_of_time(t, T_COALESCENCE, mchirp)     

        # phase(t) = phi_c - integral_t^{t_c} 2*pi*f(t') dt'
        # implemented as: integral from 0 to t_c minus integral from 0 to t,
        # via cumulative trapezoidal integration
        omega = 2 * torch.pi * f_t
        dt = DELTA_T
        cum_phase = torch.cumsum(omega, dim=-1) * dt             # integral from 0 to t
        total_phase_to_tc = cum_phase[:, -1:]                    # approx integral 0 to t_c
        phase = phi_c.unsqueeze(-1) - (total_phase_to_tc - cum_phase)

        amp_envelope = amplitude.unsqueeze(-1) * f_t ** (2.0 / 3.0)
        strain = amp_envelope * torch.cos(phase)
        return strain


