STRAIN_SCALE = 1e21
T_COALESCENCE = 3.5          
MC_MIN, MC_MAX = 5.0, 40.0
MTOT_MIN, MTOT_MAX = 20.0, 80.0
A_MIN, A_MAX = 0.1, 10.0
PHYSICS_WINDOW_T = (3.42, 3.50)   
DFDT_SCALE = 20000.0  
DELTA_T = 1.0 / 4096


def _rescale_sigmoid(raw, lo, hi):
    return lo + torch.sigmoid(raw) * (hi - lo)


class SharedEncoder(nn.Module):
    """8 Conv1d blocks (kernel=15, stride=2, pad=7) + global average pool +
    bottleneck FC. Input (batch, 1, 16384) -> latent z (batch, 128)."""

    def __init__(self):
        super().__init__()
        channels = [1, 8, 16, 32, 64, 128, 128, 256, 256]
        layers = []
        for cin, cout in zip(channels[:-1], channels[1:]):
            layers += [
                nn.Conv1d(cin, cout, kernel_size=15, stride=2, padding=7),
                nn.BatchNorm1d(cout),
                nn.LeakyReLU(0.1),
            ]
        self.conv = nn.Sequential(*layers)
        self.pool = nn.AdaptiveAvgPool1d(1)
        self.bottleneck = nn.Sequential(
            nn.Linear(256, 256), nn.ReLU(), nn.Dropout(0.2),
            nn.Linear(256, 128),
        )

    def forward(self, x):
        # x: (batch, 1, 16384)
        h = self.conv(x)                 # (batch, 256, 64)
        h = self.pool(h).squeeze(-1)     # (batch, 256)
        z = self.bottleneck(h)           # (batch, 128)
        return z


class AuxMassHeads(nn.Module):
    """Option B: total_mass and eta, ordinary supervised regression,
    NOT tied to the PN residual or generator in either model."""

    def __init__(self):
        super().__init__()
        self.total_mass_head = nn.Sequential(nn.Linear(128, 64), nn.ReLU(), nn.Linear(64, 1))
        self.eta_head = nn.Sequential(nn.Linear(128, 64), nn.ReLU(), nn.Linear(64, 1))

    def forward(self, z):
        total_mass = _rescale_sigmoid(self.total_mass_head(z), MTOT_MIN, MTOT_MAX)
        eta = torch.sigmoid(self.eta_head(z)) * 0.25
        return total_mass.squeeze(-1), eta.squeeze(-1)


def recover_component_masses(total_mass, eta):
    """Post-hoc only (ARCHITECTURE_SPEC.md 4) -- never used in training."""
    eta = torch.clamp(eta, max=0.25)
    disc = torch.sqrt(torch.clamp(1 - 4 * eta, min=0))
    m1 = (total_mass / 2) * (1 + disc)
    m2 = (total_mass / 2) * (1 - disc)
    return m1, m2


class ChirpMassHead(nn.Module):
    def __init__(self):
        super().__init__()
        self.head = nn.Sequential(nn.Linear(128, 64), nn.ReLU(), nn.Linear(64, 1))

    def forward(self, z):
        return _rescale_sigmoid(self.head(z), MC_MIN, MC_MAX).squeeze(-1)


