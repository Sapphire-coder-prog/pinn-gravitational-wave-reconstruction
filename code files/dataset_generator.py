STRAIN_SCALE = 1e21
T_COALESCENCE = 3.5          
MC_MIN, MC_MAX = 5.0, 40.0
MTOT_MIN, MTOT_MAX = 20.0, 80.0
A_MIN, A_MAX = 0.1, 10.0
PHYSICS_WINDOW_T = (3.42, 3.50)   
DFDT_SCALE = 3000.0
DELTA_T = 1.0 / 4096


def _rescale_sigmoid(raw, lo, hi):
    return lo + torch.sigmoid(raw) * (hi - lo)


class SharedEncoder(nn.Module):
    """8 Conv1d blocks (kernel=15, stride=2, pad=7) + global average pool +
    bottleneck FC. Input (batch, 1, 16384) -> latent z (batch, 128)."""

    def __init__(self):
        super().__init__()
        channels = [1, 8, 16, 32, 64, 128, 128, 256, 256]
        layers = []
        for cin, cout in zip(channels[:-1], channels[1:]):
            layers += [
                nn.Conv1d(cin, cout, kernel_size=15, stride=2, padding=7),
                nn.BatchNorm1d(cout),
                nn.LeakyReLU(0.1),
            ]
        self.conv = nn.Sequential(*layers)
        self.pool = nn.AdaptiveAvgPool1d(1)
        self.bottleneck = nn.Sequential(
            nn.Linear(256, 256), nn.ReLU(), nn.Dropout(0.2),
            nn.Linear(256, 128),
        )

    def forward(self, x):
        # x: (batch, 1, 16384)
        h = self.conv(x)                 
        h = self.pool(h).squeeze(-1)     
        z = self.bottleneck(h)           
        return z


class AuxMassHeads(nn.Module):
    """Option B: total_mass and eta, ordinary supervised regression,
    NOT tied to the PN residual or generator in either model."""

    def __init__(self):
        super().__init__()
        self.total_mass_head = nn.Sequential(nn.Linear(128, 64), nn.ReLU(), nn.Linear(64, 1))
        self.eta_head = nn.Sequential(nn.Linear(128, 64), nn.ReLU(), nn.Linear(64, 1))

    def forward(self, z):
        total_mass = _rescale_sigmoid(self.total_mass_head(z), MTOT_MIN, MTOT_MAX)
        eta = torch.sigmoid(self.eta_head(z)) * 0.25
        return total_mass.squeeze(-1), eta.squeeze(-1)


def recover_component_masses(total_mass, eta):
    """Post-hoc only (ARCHITECTURE_SPEC.md 4) -- never used in training."""
    eta = torch.clamp(eta, max=0.25)
    disc = torch.sqrt(torch.clamp(1 - 4 * eta, min=0))
    m1 = (total_mass / 2) * (1 + disc)
    m2 = (total_mass / 2) * (1 - disc)
    return m1, m2


class ChirpMassHead(nn.Module):
    def __init__(self):
        super().__init__()
        self.head = nn.Sequential(nn.Linear(128, 64), nn.ReLU(), nn.Linear(64, 1))

    def forward(self, z):
        return _rescale_sigmoid(self.head(z), MC_MIN, MC_MAX).squeeze(-1)


# ---------------------------------------------------------------------
# Soft-constrained model
# ---------------------------------------------------------------------

class Decoder(nn.Module):
    """Mirror of SharedEncoder: z (128) -> strain (16384), via FC expand +
    8 ConvTranspose1d blocks."""

    def __init__(self):
        super().__init__()
        self.fc_expand = nn.Linear(128, 256 * 64)
        channels = [256, 256, 128, 128, 64, 32, 16, 8, 1]
        layers = []
        for i, (cin, cout) in enumerate(zip(channels[:-1], channels[1:])):
            layers.append(nn.ConvTranspose1d(cin, cout, kernel_size=15, stride=2,
                                               padding=7, output_padding=1))
            if i < len(channels) - 2:  # no BN/activation on final layer
                layers += [nn.BatchNorm1d(cout), nn.LeakyReLU(0.1)]
        self.deconv = nn.Sequential(*layers)

    def forward(self, z):
        h = self.fc_expand(z).view(-1, 256, 64)
        strain = self.deconv(h).squeeze(1)   
        return strain


class SoftConstrainedModel(nn.Module):
    def __init__(self):
        super().__init__()
        self.encoder = SharedEncoder()
        self.decoder = Decoder()
        self.chirp_mass_head = ChirpMassHead()
        self.aux_heads = AuxMassHeads()

    def forward(self, noisy_strain):
        # noisy_strain: (batch, 16384), already scaled by STRAIN_SCALE
        z = self.encoder(noisy_strain.unsqueeze(1))
        recon_strain = self.decoder(z)
        chirp_mass = self.chirp_mass_head(z)
        total_mass, eta = self.aux_heads(z)
        return {
            "recon_strain": recon_strain,
            "chirp_mass": chirp_mass,
            "total_mass": total_mass,
            "eta": eta,
        }

    def physics_residual(self, recon_strain, chirp_mass):
        """Computed on the model's OWN reconstruction, per ARCHITECTURE_SPEC.md 2.3."""
        idx_lo = int(PHYSICS_WINDOW_T[0] / DELTA_T)
        idx_hi = int(PHYSICS_WINDOW_T[1] / DELTA_T)

        freq_full = instantaneous_frequency(recon_strain, DELTA_T)  # (batch, 16383)
        freq_window = freq_full[:, idx_lo:idx_hi]

        t_window = torch.arange(idx_lo, idx_hi, device=recon_strain.device, dtype=torch.float32) * DELTA_T
        dfdt_numerical = torch.gradient(freq_window, spacing=(DELTA_T,), dim=-1)[0]

        dfdt_pn = pn_dfdt(freq_window, chirp_mass.unsqueeze(-1))

        residual = torch.mean(((dfdt_numerical - dfdt_pn) / DFDT_SCALE) ** 2)
        return residual


