def chirp_mass_of(m1, m2):
    return (m1 * m2) ** 0.6 / (m1 + m2) ** 0.2


def symmetric_mass_ratio(m1, m2):
    return (m1 * m2) / (m1 + m2) ** 2


def extract_aligned_segment(hp_array, seg_len, merger_offset_samples):
    """Slice hp_array so the merger (peak amplitude) sits at
    `merger_offset_samples` within a zero-padded array of length seg_len."""
    peak_idx = int(np.argmax(np.abs(hp_array)))
    start = peak_idx - merger_offset_samples
    end = start + seg_len
    seg = np.zeros(seg_len)
    src_start, src_end = max(start, 0), min(end, len(hp_array))
    dst_start = src_start - start
    dst_end = dst_start + (src_end - src_start)
    seg[dst_start:dst_end] = hp_array[src_start:src_end]
    return seg


import time

def main():
    args = get_args()
    rng = np.random.default_rng(args.seed)

    # Ensure the base output directory exists
    os.makedirs(args.outdir, exist_ok=True)

    seg_len = int(args.seg_duration / args.delta_t)
    flen = seg_len // 2 + 1
    delta_f = 1.0 / args.seg_duration
    psd = aLIGOZeroDetHighPower(flen, delta_f, args.f_lower)
    merger_offset_samples = int(args.merger_time / args.delta_t)

    taper_n = int(args.taper_duration / args.delta_t)
    taper_window = tukey(seg_len, alpha=2 * taper_n / seg_len)

    splits = {"train": args.n_train, "val": args.n_val, "test": args.n_test}
    total_samples = sum(splits.values()) * len(args.snr_buckets)
    print(f"Generating {total_samples} samples total. Progress prints every 200 samples.")

    rows = []
    clean_arr, noisy_arr = [], []
    sample_id = 0
    t_start = time.time()

    for split, n_per_bucket in splits.items():
        for target_snr in args.snr_buckets:
            for _ in range(n_per_bucket):
                # sample non-spinning component masses, m1 >= m2, capped total mass
                while True:
                    m1, m2 = rng.uniform(args.mass_min, args.mass_max, size=2)
                    if m1 < m2:
                        m1, m2 = m2, m1
                    if m1 + m2 <= args.total_mass_max:
                        break

                mchirp = chirp_mass_of(m1, m2)
                mtot = m1 + m2
                eta = symmetric_mass_ratio(m1, m2)

                hp, _ = get_td_waveform(
                    approximant="IMRPhenomD",
                    mass1=m1, mass2=m2,
                    delta_t=args.delta_t,
                    f_lower=args.f_lower,
                    distance=100,  # fiducial; rescaled to target SNR below
                )

                clean_seg = extract_aligned_segment(hp.numpy(), seg_len, merger_offset_samples)
                clean_seg = clean_seg * taper_window

                clean_ts = TimeSeries(clean_seg, delta_t=args.delta_t)
                current_sigma = sigma(clean_ts, psd=psd, low_frequency_cutoff=args.f_lower)
                scale = target_snr / current_sigma
                clean_seg_scaled = clean_seg * scale

                noise = noise_from_psd(seg_len, args.delta_t, psd, seed=args.seed + sample_id)
                noisy_seg = clean_seg_scaled + noise.numpy()

                clean_arr.append(clean_seg_scaled.astype(np.float32))
                noisy_arr.append(noisy_seg.astype(np.float32))

                rows.append({
                    "sample_id": sample_id,
                    "split": split,
                    "mass1": m1, "mass2": m2,
                    "chirp_mass": mchirp, "total_mass": mtot, "eta": eta,
                    "target_snr": target_snr,
                })
                sample_id += 1

                if sample_id % 200 == 0 or sample_id == total_samples:
                    elapsed = time.time() - t_start
                    rate = sample_id / elapsed
                    eta = (total_samples - sample_id) / rate if rate > 0 else float("nan")
                    print(f"  {sample_id}/{total_samples} samples "
                          f"({elapsed:.1f}s elapsed, {rate:.1f} samples/s, "
                          f"ETA {eta:.0f}s / {eta/60:.1f} min)")

    meta = pd.DataFrame(rows)
    clean_arr = np.stack(clean_arr)
    noisy_arr = np.stack(noisy_arr)

    # Create the output directory if it doesn't exist
    os.makedirs(f"{args.outdir}/data", exist_ok=True)

    np.savez_compressed(
        f"{args.outdir}/data/dataset.npz",
        clean=clean_arr, noisy=noisy_arr,
        chirp_mass=meta["chirp_mass"].values,
        total_mass=meta["total_mass"].values,
        eta=meta["eta"].values,
        target_snr=meta["target_snr"].values,
        split=meta["split"].values,
        delta_t=args.delta_t, seg_duration=args.seg_duration,
        merger_time=args.merger_time, f_lower=args.f_lower,
    )
    meta.to_csv(f"{args.outdir}/data/dataset_metadata.csv", index=False)
    print(f"Saved {len(meta)} samples to data/dataset.npz and data/dataset_metadata.csv")

    make_report_figures(meta, clean_arr, noisy_arr, args)


