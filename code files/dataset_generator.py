idx = np.where(d['split'] == 'train')[0][:8]

noisy = torch.tensor(d['noisy'][idx] * STRAIN_SCALE, dtype=torch.float32)
clean = torch.tensor(d['clean'][idx] * STRAIN_SCALE, dtype=torch.float32)
mchirp_true = torch.tensor(d['chirp_mass'][idx], dtype=torch.float32)
mtot_true = torch.tensor(d['total_mass'][idx], dtype=torch.float32)
eta_true = torch.tensor(d['eta'][idx], dtype=torch.float32)

print("Batch loaded:", noisy.shape, clean.shape)
print()

# ---- SOFT MODEL ----
soft = SoftConstrainedModel()
out = soft(noisy)
print("SOFT MODEL output shapes:")
for k, v in out.items():
    print(" ", k, v.shape)

data_loss = torch.nn.functional.mse_loss(out['recon_strain'], clean)
mchirp_loss = torch.nn.functional.mse_loss(out['chirp_mass'], mchirp_true)
physics_loss = soft.physics_residual(out['recon_strain'], out['chirp_mass'])
total_loss = data_loss + mchirp_loss + 0.3 * physics_loss

print(f"data_loss={data_loss.item():.4f}  mchirp_loss={mchirp_loss.item():.4f}  "
      f"physics_loss={physics_loss.item():.4f}")

total_loss.backward()
print("Backward pass OK -- encoder received gradients:",
      sum(p.grad.norm() for p in soft.encoder.parameters() if p.grad is not None).item())
print()

# ---- HARD MODEL ----
hard = HardConstrainedModel()
out2 = hard(noisy)
print("HARD MODEL output shapes:")
for k, v in out2.items():
    print(" ", k, v.shape)

print("Any NaN in output:", torch.isnan(out2['recon_strain']).any().item())
print("Any Inf in output:", torch.isinf(out2['recon_strain']).any().item())

loss2 = (torch.nn.functional.mse_loss(out2['recon_strain'], clean)
         + torch.nn.functional.mse_loss(out2['chirp_mass'], mchirp_true))
loss2.backward()
print("Backward pass OK -- loss:", loss2.item())