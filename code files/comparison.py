G = 6.674e-11
C = 2.998e8
MSUN_KG = 1.98892e30


def chirp_mass_to_kg(mchirp_msun):
    return mchirp_msun * MSUN_KG


def pn_dfdt(f, mchirp_msun):
    """Leading-order PN df/dt (Hz/s), differentiable w.r.t. both f and
    mchirp_msun. Shapes broadcast normally (e.g. f: [B, T], mchirp_msun: [B, 1])."""
    Mc = chirp_mass_to_kg(mchirp_msun)
    return (96.0 / 5.0) * torch.pi ** (8.0 / 3.0) * (G * Mc / C ** 3) ** (5.0 / 3.0) * f ** (11.0 / 3.0)


def pn_frequency_of_time(t, t_coalescence, mchirp_msun, f_max=400.0, tau_min=0.005):
    """Closed-form leading-order frequency-vs-time-to-merger track, with the
    numerical safeguards required for use inside a generator (see
    ARCHITECTURE_SPEC.md 3.3):
      - tau is floored at tau_min (5ms) to avoid the 1/tau singularity at t_c
      - f is capped at f_max (400 Hz) as a second line of defense

    t: [B, T] or [T] time grid (same for every sample in a batch, broadcastable)
    t_coalescence: python float (fixed constant for this dataset, not learned)
    mchirp_msun: [B, 1] predicted chirp mass per sample
    Returns: f(t), same shape as broadcast(t, mchirp_msun)
    """
    Mc = chirp_mass_to_kg(mchirp_msun)
    tau = t_coalescence - t
    tau_safe = torch.clamp(tau, min=tau_min)
    f = (1.0 / torch.pi) * (G * Mc / C ** 3) ** (-5.0 / 8.0) * (5.0 / (256.0 * tau_safe)) ** (3.0 / 8.0)
    f = torch.clamp(f, max=f_max)
    return f


def isco_frequency(total_mass_msun):
    Mtot = total_mass_msun * MSUN_KG
    return C ** 3 / (6.0 ** 1.5 * torch.pi * G * Mtot)


# ---------------------------------------------------------------------
# Differentiable instantaneous-frequency extraction (Hilbert transform via FFT)
# ---------------------------------------------------------------------

def instantaneous_frequency(strain, delta_t, smooth_kernel_width=25, hilbert_taps=201):
    """Estimate the instantaneous GW frequency of a real-valued strain
    signal via the analytic signal, followed by phase unwrap and a finite
    difference. Used by the soft model's physics residual on its OWN
    reconstructed strain, so every operation here must support autograd.

    strain: [B, T] real-valued tensor
    Returns: freq [B, T-1] (Hz), one shorter than input due to the
             finite-difference derivative"""
    strain = strain.contiguous()
    strain = torch.nan_to_num(strain, nan=0.0, posinf=100.0, neginf=-100.0)  # defense in depth
    B, T = strain.shape

    # analytic signal via a fixed FIR Hilbert transformer (real conv1d only,
    # no FFT, no complex autograd)
    pad = hilbert_taps // 2
    n = torch.arange(-pad, pad + 1, device=strain.device, dtype=torch.float64)
    h = torch.zeros_like(n)
    odd_mask = (n.long() % 2 != 0)
    h[odd_mask] = -2.0 / (torch.pi * n[odd_mask])
    window = torch.hamming_window(hilbert_taps, periodic=False, dtype=torch.float64, device=strain.device)
    hilbert_kernel = (h * window).to(strain.dtype).view(1, 1, -1)

    strain_padded = torch.nn.functional.pad(strain.unsqueeze(1), (pad, pad), mode="replicate")
    hilbert_x = torch.nn.functional.conv1d(strain_padded.contiguous(), hilbert_kernel).squeeze(1).contiguous()

    phase = torch.atan2(hilbert_x, strain).contiguous()  # [B, T], wrapped to (-pi, pi]

    # differentiable phase unwrap: correct jumps > pi by adding/subtracting 2*pi,
    # implemented via cumulative sum of the wrapped jump correction (standard
    # np.unwrap algorithm, re-expressed with torch ops so it's differentiable).
    dphase = phase[:, 1:] - phase[:, :-1]
    dphase_wrapped = torch.remainder(dphase + torch.pi, 2 * torch.pi) - torch.pi
    correction = (dphase_wrapped - dphase).contiguous()
    phase_unwrapped = phase.clone()
    phase_unwrapped[:, 1:] = phase[:, 1:] + torch.cumsum(correction, dim=-1)
    phase_unwrapped = phase_unwrapped.contiguous()

    # manual finite difference instead of torch.gradient -- avoids relying
    # on torch.gradient's internal kernel behavior across torch/CUDA versions
    freq = (phase_unwrapped[:, 1:] - phase_unwrapped[:, :-1]) / (2 * torch.pi * delta_t)
    freq = freq.contiguous()

    # SANITIZE BEFORE the smoothing conv1d, not after. An untrained decoder
    # can produce near-arbitrary reconstructions, and raw finite-difference
    # frequency can be NaN/Inf as a result. On CPU that NaN just silently
    # propagates;
    freq = torch.nan_to_num(freq, nan=0.0, posinf=2000.0, neginf=-2000.0)
    freq = torch.clamp(freq, min=-2000.0, max=2000.0).contiguous()

    
    # finite-difference noise, matching the rationale in Step 3 / ARCHITECTURE_SPEC 2.3
    if smooth_kernel_width > 1:
        kernel = torch.ones(1, 1, smooth_kernel_width, device=strain.device, dtype=strain.dtype) / smooth_kernel_width
        freq_padded = torch.nn.functional.pad(
            freq.unsqueeze(1), (smooth_kernel_width // 2, smooth_kernel_width // 2), mode="replicate")
        freq = torch.nn.functional.conv1d(freq_padded.contiguous(), kernel).squeeze(1)
        freq = freq[:, :phase_unwrapped.shape[1] - 1].contiguous()  # trim to match

    # final clamp to the physically sane band (redundant with the pre-conv
    # clamp in the common case, but cheap insurance either way)
    freq = torch.nan_to_num(freq, nan=1.0, posinf=2000.0, neginf=1.0)
    freq = torch.clamp(torch.abs(freq), min=1.0, max=2000.0)
    return freq


