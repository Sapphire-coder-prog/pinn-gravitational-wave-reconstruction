class Decoder(nn.Module):
    """Mirror of SharedEncoder: z (128) -> strain (16384), via FC expand +
    8 upsample+Conv1d blocks.

    GPU note: originally used ConvTranspose1d for upsampling. After
    extensive isolation testing (bisecting via DEBUG_SKIP_PHYSICS, and
    comparing against the hard model -- which shares SharedEncoder but has
    no Decoder, and trained 22 epochs on GPU with zero crashes), the
    evidence pointed specifically at ConvTranspose1d: it's the one op type
    used here that's never appeared in a successful GPU run. Transposed
    convolutions have a real, documented history of cuDNN backward-pass
    instability on certain GPU/driver/cuDNN combinations. Replaced with the
    standard alternative: parameter-free nearest-neighbor upsampling
    (no cuDNN backward path at all) + ordinary Conv1d (the same op type
    already proven stable in SharedEncoder). Slightly more parameters
    (extra Conv1d weights vs ConvTranspose1d's fused op) but functionally
    equivalent for this purpose, and avoids the suspect op entirely.
    """

    def __init__(self):
        super().__init__()
        self.fc_expand = nn.Linear(128, 256 * 64)
        channels = [256, 256, 128, 128, 64, 32, 16, 8, 1]
        layers = []
        for i, (cin, cout) in enumerate(zip(channels[:-1], channels[1:])):
            layers.append(nn.Upsample(scale_factor=2, mode="nearest"))
            layers.append(nn.Conv1d(cin, cout, kernel_size=15, stride=1, padding=7))
            if i < len(channels) - 2:  # no BN/activation on final layer
                layers += [nn.BatchNorm1d(cout), nn.LeakyReLU(0.1)]
        self.deconv = nn.Sequential(*layers)

    def forward(self, z):
        h = self.fc_expand(z).view(-1, 256, 64)
        strain = self.deconv(h).squeeze(1)   # (batch, 16384)
        return strain


class SoftConstrainedModel(nn.Module):
    def __init__(self):
        super().__init__()
        self.encoder = SharedEncoder()
        self.decoder = Decoder()
        self.chirp_mass_head = ChirpMassHead()
        self.aux_heads = AuxMassHeads()

    def forward(self, noisy_strain):
        # noisy_strain: (batch, 16384), already scaled by STRAIN_SCALE
        z = self.encoder(noisy_strain.unsqueeze(1))
        recon_strain = self.decoder(z)
        chirp_mass = self.chirp_mass_head(z)
        total_mass, eta = self.aux_heads(z)
        return {
            "recon_strain": recon_strain,
            "chirp_mass": chirp_mass,
            "total_mass": total_mass,
            "eta": eta,
        }

    def physics_residual(self, recon_strain, chirp_mass):
        """Computed on the model's OWN reconstruction, per ARCHITECTURE_SPEC.md 2.3.

        Numerical safety (added after a real training blowup observed at
        w_physics=0.03): the previous version clamped dfdt_pn at 1e8 but
        normalized by DFDT_SCALE=3000, so even moderate PN df/dt values
        (1e4-1e5 Hz/s, realistic in this near-merger window) produced
        residual values in the thousands-to-millions -- enough to destroy
        the network in a single gradient step even at a small loss weight.
        Fixed with: (1) a tighter, more physically realistic dfdt_pn clamp,
        (2) a much larger DFDT_SCALE so typical-case residuals sit near
        O(1), and (3) an ELEMENTWISE clamp on the squared residual before
        averaging -- this bounds the worst-case contribution per sample
        while still preserving useful gradient from samples that aren't
        extreme outliers (a scalar clamp on the final mean would zero out
        gradient entirely whenever the batch-average exceeds the cap).
        """
        idx_lo = int(PHYSICS_WINDOW_T[0] / DELTA_T)
        idx_hi = int(PHYSICS_WINDOW_T[1] / DELTA_T)

        freq_full = instantaneous_frequency(recon_strain, DELTA_T)  # (batch, 16383)
        freq_window = freq_full[:, idx_lo:idx_hi].contiguous()

        dfdt_numerical = (freq_window[:, 1:] - freq_window[:, :-1]) / DELTA_T
        freq_for_pn = freq_window[:, :-1]

        dfdt_pn = pn_dfdt(freq_for_pn, chirp_mass.unsqueeze(-1))
        dfdt_pn = torch.clamp(dfdt_pn, max=1e6)  # tightened from 1e8 -- realistic peak in this band is ~1e5

        normalized_sq_error = ((dfdt_numerical - dfdt_pn) / DFDT_SCALE) ** 2
        normalized_sq_error = torch.clamp(normalized_sq_error, max=25.0)  # per-element cap, preserves gradient below it
        residual = torch.mean(normalized_sq_error)
        return residual


