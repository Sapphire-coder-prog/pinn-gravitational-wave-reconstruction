def load_model(model_type, ckpt_path, device):
    if model_type == "soft":
        model = SoftConstrainedModel().to(device)
    else:
        model = HardConstrainedModel().to(device)
    ckpt = torch.load(ckpt_path, map_location=device)
    model.load_state_dict(ckpt["model_state_dict"])
    model.eval()
    print(f"Loaded {model_type} model from {ckpt_path} "
          f"(epoch {ckpt.get('epoch', '?')}, val_loss={ckpt.get('val_loss', float('nan')):.4f})")
    return model


