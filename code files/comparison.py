def run_evaluation():
    os.makedirs(OUTDIR, exist_ok=True)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Device: {device}")

    d = np.load(DATASET_PATH, allow_pickle=True)
    test_idx = np.where(d["split"] == "test")[0]
    print(f"Test samples: {len(test_idx)}")

    noisy = d["noisy"][test_idx]
    clean = d["clean"][test_idx]
    chirp_mass_true = d["chirp_mass"][test_idx].astype(np.float32)
    total_mass_true = d["total_mass"][test_idx].astype(np.float32)
    eta_true = d["eta"][test_idx].astype(np.float32)
    target_snr = d["target_snr"][test_idx]

    models = {
        "soft": load_model("soft", SOFT_CKPT_PATH, device),
        "hard": load_model("hard", HARD_CKPT_PATH, device),
    }

    rows = []
    n = len(test_idx)
    for model_name, model in models.items():
        for start in range(0, n, BATCH_SIZE):
            end = min(start + BATCH_SIZE, n)
            batch_noisy = torch.tensor(noisy[start:end] * STRAIN_SCALE, dtype=torch.float32).to(device)

            with torch.no_grad():
                out = model(batch_noisy)

            recon = (out["recon_strain"].cpu().numpy()) / STRAIN_SCALE
            chirp_mass_pred = out["chirp_mass"].cpu().numpy()
            total_mass_pred = out["total_mass"].cpu().numpy()
            eta_pred = out["eta"].cpu().numpy()

            true_batch = clean[start:end]
            match = match_score(recon, true_batch)
            l2_err = l2_relative_error(recon, true_batch)
            mchirp_err_pct = np.abs(chirp_mass_pred - chirp_mass_true[start:end]) / chirp_mass_true[start:end] * 100
            mtot_err_pct = np.abs(total_mass_pred - total_mass_true[start:end]) / total_mass_true[start:end] * 100
            eta_err_pct = np.abs(eta_pred - eta_true[start:end]) / eta_true[start:end] * 100

            for i in range(end - start):
                rows.append({
                    "model": model_name,
                    "sample_id": test_idx[start + i],
                    "target_snr": target_snr[start + i],
                    "match": match[i],
                    "l2_relative_error": l2_err[i],
                    "chirp_mass_err_pct": mchirp_err_pct[i],
                    "total_mass_err_pct": mtot_err_pct[i],
                    "eta_err_pct": eta_err_pct[i],
                })
            print(f"  {model_name}: {end}/{n} samples evaluated", end="\r")
        print()

    results = pd.DataFrame(rows)
    results.to_csv(f"{OUTDIR}/eval_results.csv", index=False)
    print(f"Saved {OUTDIR}/eval_results.csv ({len(results)} rows)")

    summary = results.groupby(["model", "target_snr"]).agg(
        match_mean=("match", "mean"), match_std=("match", "std"),
        l2_mean=("l2_relative_error", "mean"), l2_std=("l2_relative_error", "std"),
        chirp_mass_err_mean=("chirp_mass_err_pct", "mean"), chirp_mass_err_std=("chirp_mass_err_pct", "std"),
        total_mass_err_mean=("total_mass_err_pct", "mean"),
        eta_err_mean=("eta_err_pct", "mean"),
        n=("match", "count"),
    ).reset_index()
    summary.to_csv(f"{OUTDIR}/eval_summary.csv", index=False)
    print(f"Saved {OUTDIR}/eval_summary.csv")

    make_comparison_figures(summary)
    make_convergence_figure()
    write_report_section(summary)


def make_comparison_figures(summary):
    colors = {"soft": "tab:blue", "hard": "tab:orange"}
    snr_values = sorted(summary["target_snr"].unique())

    metrics = [
        ("match_mean", "match_std", "Match (higher is better)", "fig_match_vs_snr.png"),
        ("l2_mean", "l2_std", "L2 relative error (lower is better)", "fig_l2_vs_snr.png"),
        ("chirp_mass_err_mean", "chirp_mass_err_std", "Chirp mass error (%, lower is better)", "fig_chirp_mass_err_vs_snr.png"),
    ]
    for mean_col, std_col, ylabel, fname in metrics:
        fig, ax = plt.subplots(figsize=(6, 4.5))
        for model_name in ["soft", "hard"]:
            sub = summary[summary["model"] == model_name].sort_values("target_snr")
            ax.errorbar(sub["target_snr"], sub[mean_col], yerr=sub[std_col],
                        marker="o", label=f"{model_name}-constrained", color=colors[model_name], capsize=3)
        ax.set_xlabel("Target SNR")
        ax.set_ylabel(ylabel)
        ax.set_title(ylabel.split("(")[0].strip() + " vs. SNR")
        ax.legend()
        ax.grid(alpha=0.3)
        plt.tight_layout()
        plt.savefig(f"{OUTDIR}/{fname}", dpi=150)
        plt.close(fig)
        print(f"Saved {OUTDIR}/{fname}")


def make_convergence_figure():
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
    for ax, log_path, label, color in [
        (axes[0], SOFT_LOG_PATH, "soft", "tab:blue"),
        (axes[0], HARD_LOG_PATH, "hard", "tab:orange"),
    ]:
        pass
    for log_path, label, color in [(SOFT_LOG_PATH, "soft", "tab:blue"), (HARD_LOG_PATH, "hard", "tab:orange")]:
        if not os.path.exists(log_path):
            print(f"Warning: {log_path} not found, skipping in convergence plot")
            continue
        log = pd.read_csv(log_path)
