def make_strain_reconstruction_figure(models, d, noisy, clean, target_snr, device):
    """Actual reconstructed-strain visualization: for one example sample
    per SNR bucket, plot true vs. soft-reconstructed vs. hard-reconstructed
    strain, zoomed to the pre-merger/merger region (where the interesting
    structure is -- the full 4s segment is mostly flat outside this window).
    """
    merger_time = float(d["merger_time"])
    delta_t = float(d["delta_t"])
    zoom_start = merger_time - 0.4
    zoom_end = merger_time + 0.05
    idx_lo = int(zoom_start / delta_t)
    idx_hi = int(zoom_end / delta_t)
    t_axis = np.arange(idx_lo, idx_hi) * delta_t

    snr_values = sorted(np.unique(target_snr))
    fig, axes = plt.subplots(len(snr_values), 1, figsize=(10, 2.6 * len(snr_values)), sharex=True)
    if len(snr_values) == 1:
        axes = [axes]

    for ax, snr in zip(axes, snr_values):
        candidate_idx = np.where(target_snr == snr)[0]
        if len(candidate_idx) == 0:
            continue
        example_idx = candidate_idx[0]  # first example in this SNR bucket -- deterministic, reproducible

        sample_noisy = torch.tensor(noisy[example_idx:example_idx + 1] * STRAIN_SCALE, dtype=torch.float32).to(device)
        true_strain = clean[example_idx]

        recon_by_model = {}
        with torch.no_grad():
            for model_name, model in models.items():
                out = model(sample_noisy)
                recon_by_model[model_name] = (out["recon_strain"].cpu().numpy()[0]) / STRAIN_SCALE

        ax.plot(t_axis, true_strain[idx_lo:idx_hi], color="black", lw=2.0, label="True (clean)", alpha=0.85)
        ax.plot(t_axis, recon_by_model["soft"][idx_lo:idx_hi], color="tab:blue", lw=1.3, ls="--", label="Soft-constrained")
        ax.plot(t_axis, recon_by_model["hard"][idx_lo:idx_hi], color="tab:orange", lw=1.3, ls=":", label="Hard-constrained")
        ax.axvline(merger_time, color="gray", ls=":", alpha=0.5, lw=0.8)
        ax.set_ylabel(f"SNR {snr:g}\nStrain")
        ax.legend(loc="upper left", fontsize=8)
        ax.grid(alpha=0.2)

    axes[-1].set_xlabel("Time (s)")
    fig.suptitle("Example reconstructions vs. true strain (zoomed to pre-merger/merger region)")
    plt.tight_layout()
    plt.savefig(f"{OUTDIR}/fig_strain_reconstruction_examples.png", dpi=150)
    plt.close(fig)
    print(f"Saved {OUTDIR}/fig_strain_reconstruction_examples.png")


def robust_read_csv(log_path):
    """Read a training log CSV defensively. Google Drive-synced files can
    occasionally be corrupted/incompletely synced (a real case: a file at
    a path under '.ipynb_checkpoints' failed with UnicodeDecodeError,
    'invalid start byte' -- not something a plain-ASCII CSV written by our
    own training script should ever produce, suggesting a sync/storage
    issue rather than a code bug). Tries utf-8, then latin-1 (which never
    rejects any byte value, so it always succeeds structurally even if a
    few characters are wrong), then gives up and returns None so the
    calling code can skip this log rather than crashing the whole script.
    """
    for encoding in ["utf-8", "latin-1"]:
        try:
            return pd.read_csv(log_path, encoding=encoding)
        except (UnicodeDecodeError, pd.errors.ParserError) as e:
            print(f"  Warning: failed to read {log_path} with encoding={encoding}: {e}")
    print(f"  Warning: could not read {log_path} with any encoding -- skipping it. "
          f"Check whether this file is fully synced (this looked like Drive sync "
          f"corruption, not a normal CSV format issue).")
    return None


