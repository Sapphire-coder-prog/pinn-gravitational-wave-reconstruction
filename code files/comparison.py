def recover_component_masses_np(total_mass, eta):
    """numpy equivalent of pinn_models.recover_component_masses (which is
    torch-only) -- used here since results are aggregated as numpy/pandas
    after leaving the model. Same algebra: given total mass and symmetric
    mass ratio eta = m1*m2/(m1+m2)^2, solve the quadratic for m1, m2.
    Applied to both predicted AND true (total_mass, eta) -- the dataset
    stores total_mass/eta directly (not mass1/mass2), so "true" m1/m2 here
    are recovered via this same algebra from the true labels, which is
    exact (up to float precision) since total_mass/eta were themselves
    computed from the original mass1/mass2 in 02_generate_dataset.py.
    """
    eta = np.clip(eta, 1e-8, 0.25)
    disc = np.sqrt(np.clip(1 - 4 * eta, 0, None))
    m1 = (total_mass / 2) * (1 + disc)
    m2 = (total_mass / 2) * (1 - disc)
    return m1, m2


