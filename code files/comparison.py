def match_score(recon, true, max_shift=50):
    """Time-shift-maximized normalized correlation (a simplified match
    statistic -- true matched-filter overlap would also maximize over
    phase via a Hilbert-transform quadrature term, but this captures the
    dominant effect: small time misalignment shouldn't be punished as
    reconstruction error the way raw L2 does).

    recon, true: [B, T] numpy arrays. Returns: [B] array in [-1, 1]
    (typically compared as absolute value, since an overall sign flip is
    not physically meaningful for this purpose).
    """
    B, T = recon.shape
    best = np.full(B, -1.0)
    recon_norm = np.linalg.norm(recon, axis=1) + 1e-30
    true_norm = np.linalg.norm(true, axis=1) + 1e-30
    for shift in range(-max_shift, max_shift + 1):
        if shift >= 0:
            r = recon[:, shift:]
            t = true[:, :T - shift] if shift > 0 else true
        else:
            r = recon[:, :T + shift]
            t = true[:, -shift:]
        if r.shape[1] == 0:
            continue
        num = np.sum(r * t, axis=1)
        denom = (np.linalg.norm(r, axis=1) + 1e-30) * (np.linalg.norm(t, axis=1) + 1e-30)
        # explicit zero-guard: with float32 arithmetic, denom can still
        # underflow to exact 0.0 even with the epsilon above (seen in
        # practice with an undertrained hard model producing near-zero
        # amplitude output for some samples). np.where here guarantees no
        # NaN/Inf ever enters `best`, rather than relying on the epsilon
        # alone -- a "no match" (0.0) is the correct fallback for a
        # genuinely zero-amplitude reconstruction.
        with np.errstate(divide="ignore", invalid="ignore"):
            corr = np.where(denom > 1e-25, num / denom, 0.0)
        best = np.maximum(best, np.abs(corr))
    return best


def l2_relative_error(recon, true):
    """||recon - true||_2 / ||true||_2, per sample."""
    num = np.linalg.norm(recon - true, axis=1)
    denom = np.linalg.norm(true, axis=1) + 1e-30
    return num / denom


